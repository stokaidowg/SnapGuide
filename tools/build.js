// node build.js [outDir]: builds every route listed in route/order.txt, in order, into
// SnapGuide route files, and prints the builder's report.
const fs = require('fs');
const path = require('path');
const { lua } = require('./pfdb');
lua(fs.readFileSync(__dirname + '/route-build.lua', 'utf8') + '\nreturn "ok"');
const outDir = process.argv[2] || path.join(__dirname, 'out');
fs.mkdirSync(outDir, { recursive: true });
const order = fs.readFileSync(path.join(__dirname, 'route', 'order.txt'), 'utf8').split(/\r?\n/).map(s => s.trim()).filter(s => s && !s.startsWith('#'));
const toc = [];
for (const name of order) {
  const spec = fs.readFileSync(path.join(__dirname, 'route', name + '.txt'), 'utf8');
  const res = lua('SPEC = ' + JSON.stringify(spec) +'\nlocal code, report = Build(SPEC)\nCODE = code\nreturn report');
  const code = lua('return CODE');
  fs.writeFileSync(path.join(outDir, name + '.lua'), '-- generated by the SnapGuide route builder from route/' + name + '.txt\n' + code);
  toc.push('Routes\\' + name + '.lua');
  console.log(res);
}
fs.writeFileSync(path.join(outDir, 'routes.txt'), toc.join('\n') + '\n');
// write the add-on's .toc: header, then every route in order
const tocPath = path.join(outDir, '..', 'SnapGuide.toc');
if (fs.existsSync(path.join(__dirname, 'toc-head.txt')) && process.argv[2]) {
  fs.writeFileSync(tocPath, fs.readFileSync(path.join(__dirname, 'toc-head.txt'), 'utf8') + toc.join('\n') + '\n');
}
// step numbers may have moved: paths made for steps that changed are ignored in game until
// they're made again
console.log('Now run: node paths.js   (walking paths round cliffs for the rebuilt routes, about a minute)');
