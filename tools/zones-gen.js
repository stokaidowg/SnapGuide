// SnapGuide zones.lua: every outdoor zone's world bounds from the client's WorldMapArea.dbc
// (patch-4, the newest), named the way pfQuest (and GetRealZoneText) name them
const fs = require('fs');
const { lua } = require('./pfdb');
const b = fs.readFileSync('mpqout/wma/patch-4.mpq.dbc');
let s = b.length;
while (s > 0 && (b[s - 1] === 0 || (b[s - 1] >= 32 && b[s - 1] < 127))) s--;
while ((s - 20) % 32 !== 0) s++;
const rows = [];
for (let i = 0; i < (s - 20) / 32; i++) {
  const o = 20 + i * 32;
  const map = b.readUInt32LE(o + 4), area = b.readUInt32LE(o + 8);
  const f = [16, 20, 24, 28].map(k => +b.readFloatLE(o + k).toFixed(2));
  if ((map === 0 || map === 1) && area > 0 && f[0] !== f[1]) rows.push({ map, area, f });
}
const names = JSON.parse(lua('local t = {} for id, n in pairs(ZN) do t[#t + 1] = string.format("%q:%q", tostring(id), (string.gsub(n, "%s+$", ""))) end return "{" .. table.concat(t, ",") .. "}"'));
const out = ['-- generated by tools/zones-gen.js from the client\'s WorldMapArea.dbc (patch-4.mpq):',
  '-- zone = { continent (0 Eastern Kingdoms, 1 Kalimdor), left, right, top, bottom } in world',
  '-- yards, so the arrow can point across zone borders',
  'SnapGuide.ZONES = {'];
const missing = [];
for (const r of rows.sort((a, b) => (names[a.area] || '').localeCompare(names[b.area] || ''))) {
  const n = names[r.area];
  if (!n) { missing.push(r.area); continue; }
  out.push(`  [${JSON.stringify(n)}] = { ${r.map}, ${r.f.join(', ')} },`);
}
out.push('}');
fs.writeFileSync(process.argv[2], out.join('\n') + '\n');
console.log(rows.length - missing.length, 'zones; no name for areas', missing.join(','));
